"""Check PDF content/links against exact source text; visual QA is separate."""

import hashlib
import json
from pathlib import Path
import re

import pymupdf
from pypdf import PdfReader


PACKAGE = Path(__file__).resolve().parents[2]
ROOT = PACKAGE.parent
EVIDENCE = PACKAGE / "evidence"
QA = EVIDENCE / "report-qa"


def compact(text):
    return re.sub(r"\s+", "", text)


def text_without_footer(reader):
    pages = []
    for page in reader.pages:
        text = page.extract_text() or ""
        text = re.sub(r"Software Engineering Assignment 03 \| Boranov Daniyar \| 24B031718\n\d+\n", "", text)
        pages.append(text)
    return "\n".join(pages)


main_path = PACKAGE / "A3_Boranov_Daniyar_Report.pdf"
ai_path = PACKAGE / "AI_Evidence.pdf"
main_reader, ai_reader = PdfReader(main_path), PdfReader(ai_path)
main_text, ai_text = text_without_footer(main_reader), text_without_footer(ai_reader)
build = json.loads((QA / "report-build.json").read_text(encoding="utf-8"))
access = json.loads((EVIDENCE / "prototype-access.json").read_text(encoding="utf-8"))

source_checks = {}
for path in sorted((EVIDENCE / "ai-exchanges").glob("0[1-6]-*-*.txt")):
    if path.name.endswith(("-prompt.txt", "-response.txt")):
        source_checks[path.name] = compact(path.read_text(encoding="utf-8")) in compact(ai_text)

baseline_checks = {}
for key, value in build["approved_baseline"].items():
    value = value.replace("**", "")
    if key == "contract":
        value = value.replace("`", "")
    if key == "assumptions":
        value = "\n".join(line[2:] if line.startswith("- ") else line for line in value.splitlines())
        actual = main_text.replace("•", "")
    else:
        actual = main_text
    baseline_checks[key] = compact(value) in compact(actual)

bad_phrases = ["The student has not confirmed", "The student selected", "AI completed the entire assignment",
               "The student delegated this task", "Student decision pending", "AI-drafted explanation for student review",
               "Submission status", "Actual student response", "This text was generated by an AI", "Student action required"]
violations = [phrase for phrase in bad_phrases if phrase.casefold() in main_text.casefold()]
link_checks = {}
for path, reader in ((main_path, main_reader), (ai_path, ai_reader)):
    uris = [str(a.get_object().get("/A", {}).get("/URI")) for pg in reader.pages
            for a in pg.get("/Annots", []) if a.get_object().get("/A", {}).get("/URI")]
    link_checks[path.name] = {key: access[key] in uris for key in ("bolt_project_url", "public_demo_url", "github_repository_url")}

out_of_page_spans = []
for path in (main_path, ai_path):
    doc = pymupdf.open(path)
    for i, page in enumerate(doc):
        for block in page.get_text("dict")["blocks"]:
            for line in block.get("lines", []):
                for span in line.get("spans", []):
                    x0, y0, x1, y1 = span["bbox"]
                    if min(x0, y0) < 0 or x1 > page.rect.width + 0.5 or y1 > page.rect.height + 0.5:
                        out_of_page_spans.append({"file": path.name, "page": i + 1, "text": span["text"]})

record = {
    "main_pages": len(main_reader.pages), "ai_pages": len(ai_reader.pages),
    "exact_prompt_response_text_present_ignoring_layout_whitespace": source_checks,
    "supplied_baseline_text_present_ignoring_layout_whitespace": baseline_checks,
    "required_clickable_links": link_checks,
    "banned_main_report_phrases": violations,
    "out_of_page_text_spans": out_of_page_spans,
    "pdf_sha256": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in (main_path, ai_path)},
    "reflection_words": build["reflection_word_count"],
}
(QA / "report-content-checks.json").write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
print(json.dumps(record, indent=2))
assert all(source_checks.values()), "Exact exchange content missing from PDF extraction"
assert all(baseline_checks.values()), "Supplied baseline content missing"
assert all(all(v.values()) for v in link_checks.values()), "Clickable access link missing"
assert not violations and not out_of_page_spans
assert len(main_reader.pages) == 10 and 100 <= build["reflection_word_count"] <= 200
